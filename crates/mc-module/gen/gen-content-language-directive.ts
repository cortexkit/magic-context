/**
 * Generate the Rust content-language resolver and its TypeScript differential fixture.
 *
 * Run:        bun crates/mc-module/gen/gen-content-language-directive.ts
 * Drift check: bun crates/mc-module/gen/gen-content-language-directive.ts --check
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pluginDir = join(import.meta.dir, "..", "..", "..", "packages", "plugin");
const resolve = (modulePath: string) => Bun.resolveSync(modulePath, pluginDir);

const languageMod = await import(resolve("./src/agents/language-directive"));
const validationMod = await import(
    resolve("./src/hooks/magic-context/compartment-runner-validation")
);

const { buildContentLanguageDirective, resolveLanguageName } = languageMod as {
    buildContentLanguageDirective: (
        language?: string,
        options?: { preserveUserQuotes?: boolean; retrospective?: boolean },
    ) => string;
    resolveLanguageName: (language?: string) => string;
};
const { buildHistorianRepairPrompt } = validationMod as {
    buildHistorianRepairPrompt: (
        originalPrompt: string,
        previousOutput: string,
        validationError: string,
        language?: string,
    ) => string;
};

interface LanguageNameCase {
    language: string;
    name: string;
}

interface DirectiveCase {
    label: string;
    language: string | null;
    preserve_user_quotes: boolean;
    retrospective: boolean;
    directive: string;
}

interface RepairCase {
    language: string | null;
    original_prompt: string;
    previous_output: string;
    validation_error: string;
    prompt: string;
}

const alphabet = "abcdefghijklmnopqrstuvwxyz";
const languageNames: LanguageNameCase[] = [];
for (const first of alphabet) {
    for (const second of alphabet) {
        const language = `${first}${second}`;
        const name = resolveLanguageName(language);
        if (name) languageNames.push({ language, name });
    }
}

const directiveCaseSpecs: Array<Omit<DirectiveCase, "directive">> = [
    { label: "unset", language: null, preserve_user_quotes: false, retrospective: false },
    {
        label: "unset preserves quotes",
        language: null,
        preserve_user_quotes: true,
        retrospective: false,
    },
    { label: "Turkish", language: "tr", preserve_user_quotes: false, retrospective: false },
    {
        label: "Turkish preserves quotes",
        language: "tr",
        preserve_user_quotes: true,
        retrospective: false,
    },
    {
        label: "Norwegian Bokmal",
        language: "nb",
        preserve_user_quotes: false,
        retrospective: false,
    },
    {
        label: "Norwegian Bokmal preserves quotes",
        language: "nb",
        preserve_user_quotes: true,
        retrospective: false,
    },
    {
        label: "Turkish retrospective",
        language: "tr",
        preserve_user_quotes: false,
        retrospective: true,
    },
    {
        label: "Turkish preserves quotes and retrospective",
        language: "tr",
        preserve_user_quotes: true,
        retrospective: true,
    },
];
const directiveCases = directiveCaseSpecs.map((spec) => ({
    ...spec,
    directive: buildContentLanguageDirective(spec.language ?? undefined, {
        preserveUserQuotes: spec.preserve_user_quotes,
        retrospective: spec.retrospective,
    }),
}));

const repairCases: RepairCase[] = [null, "tr", "nb"].map((language) => {
    const original_prompt = "<new_messages>\n[1] U: Preserve this quotation\n</new_messages>\n\nTranscript guard.";
    const previous_output = "<output><compartment>invalid</compartment></output>";
    const validation_error = "missing required raw ordinal";
    return {
        language,
        original_prompt,
        previous_output,
        validation_error,
        prompt: buildHistorianRepairPrompt(
            original_prompt,
            previous_output,
            validation_error,
            language ?? undefined,
        ),
    };
});

function renderRustResolver(names: readonly LanguageNameCase[]): string {
    const arms = names
        .map(({ language, name }) => `        ${JSON.stringify(language)} => Some(${JSON.stringify(name)}),`)
        .join("\n");
    return `// @generated by gen/gen-content-language-directive.ts; do not edit by hand.\n\n/// Resolve the TypeScript language-directive target for a two-letter code.\npub(crate) fn resolve_language_name(language: Option<&str>) -> Option<&'static str> {\n    let code = language?.trim();\n    if code.len() != 2 || !code.bytes().all(|byte| byte.is_ascii_alphabetic()) {\n        return None;\n    }\n\n    match code.to_ascii_lowercase().as_str() {\n${arms}\n        _ => None,\n    }\n}\n`;
}

const fixture = `${JSON.stringify(
    {
        language_names: languageNames,
        directive_cases: directiveCases,
        repair_cases: repairCases,
    },
    null,
    2,
)}\n`;
const rustResolver = renderRustResolver(languageNames);
const fixturePath = join(import.meta.dir, "..", "testdata", "content-language-directive-golden.json");
const resolverPath = join(import.meta.dir, "..", "src", "content_language.rs");

if (process.argv.includes("--check")) {
    const expected = [
        [fixturePath, fixture],
        [resolverPath, rustResolver],
    ] as const;
    for (const [path, content] of expected) {
        if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
            console.error(`content-language directive drifted; regenerate ${path}`);
            process.exit(1);
        }
    }
    console.log("content-language directive fixture and resolver are up to date");
} else {
    writeFileSync(fixturePath, fixture);
    writeFileSync(resolverPath, rustResolver);
    console.log(
        `wrote ${languageNames.length} language names and ${directiveCases.length} directive cases`,
    );
}
